import re,json,sys
B='/home/claude/src/'
old=open(B+'calendar/src/commonMain/kotlin/io/github/persiancalendar/calendar/persian/OldEraConverter.kt',encoding='utf8').read()
m=re.search(r'val monthLength = listOf\((.*?)\n        \)',old,re.S).group(1)
months=[int(x) for x in re.findall(r'(?<![/*\d])\b(\d\d)\b(?![*/])',re.sub(r'/\*.*?\*/','',m))]
assert len(months)%12==0,len(months); print('old-era years',len(months)//12)
lk=open(B+'calendar/src/commonMain/kotlin/io/github/persiancalendar/calendar/persian/LookupTableConverter.kt',encoding='utf8').read()
leaps=re.search(r'val leapYears = intArrayOf\((.*?)\n        \)',lk,re.S).group(1)
leaps=[int(x) for x in re.findall(r'\b1[2-9]\d\d\b',re.sub(r'//.*','',leaps))]
print('leaps',leaps[0],leaps[-1],len(leaps))
hj=open(B+'calendar/src/commonMain/kotlin/io/github/persiancalendar/calendar/islamic/IranianIslamicDateConverter.kt',encoding='utf8').read()
rows=re.findall(r'/\*(\d{4})\*/\s*0b([01_]+)',hj)
hij=[]
for y,bits in rows:
    b=bits.replace('_','')
    hij.append((int(y),b))
print('hijri rows',len(hij),hij[0],hij[-1],[ (y,len(b)) for y,b in hij if len(b)!=12][:5])
# the 1448 row has "_____" placeholders -> handle: pad
ys=[y for y,_ in hij]; assert ys==list(range(ys[0],ys[0]+len(ys))),'non contiguous'
# equinox
eq=open(B+'equinox/src/commonMain/kotlin/io/github/persiancalendar/equinox/Equinox.kt',encoding='utf8').read()
def arr(name):
    s=re.search(r'val '+name+r' = doubleArrayOf\((.*?)\n        \)',eq,re.S).group(1)
    return [float(x) for x in re.findall(r'-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?',s)]
L,R,N=arr('EARTH_L'),arr('EARTH_R'),arr('NUT_TERMS')
print(len(L),len(R),len(N))
ls=re.findall(r'Triple\((\d+), (\d+), (\d+)\)',eq)
out='/* Generated by tools/gen_tables.py — data tables derived from open data (see About). */\n'
out+='var T_LEAPS='+json.dumps(leaps,separators=(',',':'))+';\n'
out+='var T_HIJRI_START='+str(hij[0][0])+';\nvar T_HIJRI='+json.dumps([b for _,b in hij],separators=(',',':'))+';\n'
out+='var T_EARTH_L='+json.dumps(L,separators=(',',':'))+';\nvar T_EARTH_R='+json.dumps(R,separators=(',',':'))+';\nvar T_NUT='+json.dumps(N,separators=(',',':'))+';\n'
out+='var T_LEAPSEC='+json.dumps([[int(a),int(b),int(c)] for a,b,c in ls],separators=(',',':'))+';\n'
open('js/tables.js','w',encoding='utf8').write(out); print(len(out))
